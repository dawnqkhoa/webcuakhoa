-- Chạy toàn bộ nội dung trong Supabase > SQL Editor > New query.
-- Server sử dụng SUPABASE_SERVICE_ROLE_KEY chỉ ở backend; tuyệt đối không đưa khóa này lên GitHub/frontend.
create table if not exists public.notes (
 id bigint generated by default as identity primary key,
 text text not null check (char_length(text) between 1 and 280),
 author text not null default 'Ẩn danh',
 delete_password_hash text not null,
 created_at timestamptz not null default now()
);
alter table public.notes add column if not exists author text not null default 'Ẩn danh';
alter table public.notes add column if not exists delete_password_hash text;

create table if not exists public.moods (
 id bigint generated by default as identity primary key,
 mood text not null check (mood in ('bực mình','muốn ôm','nhớ cậu')),
 level integer not null check (level between 1 and 5),
 intensity text not null,
 created_at timestamptz not null default now()
);
create table if not exists public.letters (
 id bigint generated by default as identity primary key,
 sender text not null check (char_length(sender) between 1 and 40),
 subject text not null check (char_length(subject) between 1 and 80),
 body text not null check (char_length(body) between 1 and 10000),
 password_hash text not null,
 created_at timestamptz not null default now()
);
alter table public.notes enable row level security;
alter table public.moods enable row level security;
alter table public.letters enable row level security;
-- Không tạo policy anon/public. Các thao tác được thực hiện qua server bằng service-role key giữ kín.
